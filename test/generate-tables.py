#!/usr/bin/env python3
"""Regenerate the IRS life-expectancy data from primary sources.

1. src/joint-table.ts — the Joint and Last Survivor Table, extracted
   mechanically from the eCFR XML of 26 CFR 1.401(a)(9)-9(d):
     curl --compressed -o s9.xml \
       'https://www.ecfr.gov/api/versioner/v1/full/2026-01-01/title-26.xml?section=1.401(a)(9)-9'
   Also checks that the Single Life (b) and Uniform Lifetime (c) tables in
   that XML equal the ones in src/index.ts (printed as JSON for comparison).

2. test/fixtures/pub590b-2025.json — Tables I, II and III as printed in IRS
   Publication 590-B (2025), from text extracted with pypdf:
     python -c "import pypdf,sys; print('\\n'.join(p.extract_text() for p in pypdf.PdfReader(sys.argv[1]).pages))" p590b.pdf > p590b.txt

Usage: python3 test/generate-tables.py s9.xml p590b.txt
"""
import html
import json
import re
import sys

xml_path, pub_path = sys.argv[1], sys.argv[2]


def age(s):
    return 120 if s.startswith("120") else int(s)


# ---- 1. eCFR -------------------------------------------------------------
t = open(xml_path, encoding="utf-8").read()


def cells(row, tag):
    return [html.unescape(re.sub(r"<[^>]+>", "", c)).strip()
            for c in re.findall(rf"<{tag}[^>]*>(.*?)</{tag}>", row, re.S)]


tables = []
for tb in re.findall(r"<TABLE.*?</TABLE>", t, re.S):
    head = [cells(r, "TH") for r in re.findall(r"<TR>(.*?)</TR>", re.search(r"<THEAD>(.*?)</THEAD>", tb, re.S).group(1), re.S)]
    rows = [cells(r, "TD") for r in re.findall(r"<TR>(.*?)</TR>", re.search(r"<TBODY>(.*?)</TBODY>", tb, re.S).group(1), re.S)]
    tables.append((head, rows))

single = {age(a): float(v) for a, v in tables[0][1]}
uniform = {age(a): float(v) for a, v in tables[1][1]}
joint = {}
for head, rows in tables[2:-1]:  # the last table is the mortality rates (e)
    cols = head[0][1:]
    for r in rows:
        for c, v in zip(cols, r[1:]):
            if c and v:
                joint[(age(r[0]), age(c))] = float(v)
assert len(single) == 121 and len(uniform) == 49

# Lower triangle (row = older age). The eCFR rendering drops cell (19, 35)
# at a page break; (35, 19) is present. The regulation prints (2, 5) = 88.5
# but (5, 2) = 88.6 — the only asymmetric pair; the row-5 value is used.
B36 = "0123456789abcdefghijklmnopqrstuvwxyz"
out = []
for a in range(121):
    for b in range(a + 1):
        v = joint.get((a, b), joint.get((b, a)))
        n = round(v * 10)
        assert 0 < n < 36 * 36
        out.append(B36[n // 36] + B36[n % 36])
data = "".join(out)

with open("src/joint-table.ts", "w", encoding="utf-8") as fh:
    fh.write(
        "// GENERATED by test/generate-tables.py from the eCFR XML of\n"
        "// 26 CFR 1.401(a)(9)-9(d) (Joint and Last Survivor Table, applicable to\n"
        "// distribution calendar years beginning on/after 2022-01-01). Do not edit.\n"
        "//\n"
        "// Lower triangle, row-major: entry for ages (a, b) with a >= b is at index\n"
        "// a*(a+1)/2 + b; each entry is two base-36 digits of the divisor x 10.\n"
        "// Age 120 stands for \"120 and older\".\n"
        f"export const JOINT_TABLE_DATA =\n  \"{data}\";\n"
    )
print(json.dumps({"single": single, "uniform": uniform}))

# ---- 2. Pub 590-B ------------------------------------------------------------
num = r"\d+\.\d"
pub = {"I": {}, "II": {}, "III": {}}
mode, cols = None, None
for ln in open(pub_path, encoding="utf-8").read().split("\n"):
    s = ln.strip()
    if s.startswith("Table III"):
        mode = "III"
    elif s.startswith("Table II"):
        mode = "II"
    elif s.startswith("Table I"):
        mode = "I"
    elif s.startswith("Appendix C"):
        mode = None
    if mode in ("I", "III"):
        m = re.fullmatch(rf"(\d+\+?)\s+({num})(?:\s+(\d+\+?|120 and over)\s+({num}))?", s)
        if m:
            pub[mode][age(m[1])] = float(m[2])
            if m[3]:
                pub[mode][age(m[3])] = float(m[4])
    elif mode == "II":
        if s.startswith("Ages"):
            cols = [age(c) for c in s.split()[1:]]
        elif cols:
            m = re.fullmatch(rf"(\d+\+?)((?:\s+{num})+)", s)
            if m:
                vals = [float(v) for v in m[2].split()]
                assert len(vals) == len(cols), s
                for c, v in zip(cols, vals):
                    pub["II"][f"{age(m[1])},{c}"] = v

with open("test/fixtures/pub590b-2025.json", "w", encoding="utf-8") as fh:
    json.dump({
        "source": "IRS Publication 590-B (2025), Appendix B, Tables I-III, text extracted with pypdf",
        "tableI": pub["I"], "tableII": pub["II"], "tableIII": pub["III"],
    }, fh, separators=(",", ":"))
print(f"pub590b: I={len(pub['I'])} II={len(pub['II'])} III={len(pub['III'])}", file=sys.stderr)
